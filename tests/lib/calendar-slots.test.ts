import { computeSlots, buildGCalUrl, buildICS } from "@/lib/calendar-slots";
import type {
  AvailabilityRule,
  AppointmentBrief,
  CalendarBlock,
} from "@/lib/calendar-slots";

// ─────────────────────────────────────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────────────────────────────────────

function makeRule(
  overrides: Partial<AvailabilityRule> & {
    weekday: number;
    start_time: string;
    end_time: string;
    slot_minutes: number;
  }
): AvailabilityRule {
  return {
    id: "rule-1",
    effective_from: "2020-01-01",
    effective_to: null,
    ...overrides,
  };
}

/** Monday 2024-06-10 */
const MON = new Date("2024-06-10T00:00:00");
/** Next Friday 2024-06-14 */
const FRI = new Date("2024-06-14T00:00:00");

// ─────────────────────────────────────────────────────────────────────────────
// computeSlots
// ─────────────────────────────────────────────────────────────────────────────

describe("computeSlots", () => {
  it("returns empty array when there are no rules", () => {
    const slots = computeSlots([], MON, FRI, [], []);
    expect(slots).toHaveLength(0);
  });

  it("generates slots for a single weekday rule (Monday, 30-min)", () => {
    const rule = makeRule({ weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const slots = computeSlots([rule], MON, FRI, [], []);
    expect(slots).toHaveLength(2);
    expect(slots[0].status).toBe("available");
    expect(slots[0].startsAt.getHours()).toBe(9);
    expect(slots[0].startsAt.getMinutes()).toBe(0);
    expect(slots[1].startsAt.getMinutes()).toBe(30);
  });

  it("generates slots for a 60-min rule", () => {
    const rule = makeRule({ weekday: 1, start_time: "09:00", end_time: "12:00", slot_minutes: 60 });
    const slots = computeSlots([rule], MON, FRI, [], []);
    expect(slots).toHaveLength(3);
  });

  it("does not exceed window end (no partial slots)", () => {
    // 09:00–10:30 with 60-min slots → only 1 slot (09:00-10:00); 10:00-11:00 exceeds window.
    const rule = makeRule({
      weekday: 1,
      start_time: "09:00",
      end_time: "10:30",
      slot_minutes: 60,
    });
    const slots = computeSlots([rule], MON, FRI, [], []);
    expect(slots).toHaveLength(1);
    expect(slots[0].endsAt.getHours()).toBe(10);
  });

  it("marks slot as 'requested' when a requested appointment overlaps", () => {
    const rule = makeRule({ weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    // Derive actual local slot times from a baseline run to avoid timezone mismatches.
    const baseline = computeSlots([rule], MON, FRI, [], []);
    const appt: AppointmentBrief = {
      id: "appt-1",
      starts_at: baseline[0].startsAt.toISOString(),
      ends_at: baseline[0].endsAt.toISOString(),
      status: "requested",
    };
    const [first, second] = computeSlots([rule], MON, FRI, [appt], []);
    expect(first.status).toBe("requested");
    expect(first.appointmentId).toBe("appt-1");
    expect(second.status).toBe("available");
  });

  it("marks slot as 'confirmed' when a confirmed appointment overlaps", () => {
    const rule = makeRule({ weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const baseline = computeSlots([rule], MON, FRI, [], []);
    const appt: AppointmentBrief = {
      id: "appt-2",
      starts_at: baseline[0].startsAt.toISOString(),
      ends_at: baseline[0].endsAt.toISOString(),
      status: "confirmed",
    };
    const [first] = computeSlots([rule], MON, FRI, [appt], []);
    expect(first.status).toBe("confirmed");
  });

  it("does not block slots for completed/canceled/no_show appointments", () => {
    const rule = makeRule({ weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const baseline = computeSlots([rule], MON, FRI, [], []);
    const appt: AppointmentBrief = {
      id: "appt-3",
      starts_at: baseline[0].startsAt.toISOString(),
      ends_at: baseline[0].endsAt.toISOString(),
      status: "completed",
    };
    const slots = computeSlots([rule], MON, FRI, [appt], []);
    expect(slots.every((s) => s.status === "available")).toBe(true);
  });

  it("skips slots covered by a calendar block", () => {
    const rule = makeRule({ weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const baseline = computeSlots([rule], MON, FRI, [], []);
    const block: CalendarBlock = {
      starts_at: baseline[0].startsAt.toISOString(),
      ends_at: baseline[0].endsAt.toISOString(),
    };
    const slots = computeSlots([rule], MON, FRI, [], [block]);
    expect(slots).toHaveLength(1);
    expect(slots[0].startsAt.getMinutes()).toBe(baseline[1].startsAt.getMinutes());
  });

  it("deduplicates slots generated by overlapping rules", () => {
    const r1 = makeRule({ id: "r1", weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const r2 = makeRule({ id: "r2", weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const slots = computeSlots([r1, r2], MON, FRI, [], []);
    expect(slots).toHaveLength(2); // not doubled
  });

  it("respects effective_from date — skips days before rule is active", () => {
    // Rule starts Tuesday 2024-06-11; queries from Monday.
    const rule = makeRule({
      weekday: 1, // Monday
      start_time: "09:00",
      end_time: "10:00",
      slot_minutes: 30,
      effective_from: "2024-06-17", // next Monday
    });
    const slots = computeSlots([rule], MON, FRI, [], []);
    expect(slots).toHaveLength(0);
  });

  it("respects effective_to date — skips days after rule expires", () => {
    const rule = makeRule({
      weekday: 1,
      start_time: "09:00",
      end_time: "10:00",
      slot_minutes: 30,
      effective_from: "2020-01-01",
      effective_to: "2024-06-09", // day before MON
    });
    const slots = computeSlots([rule], MON, FRI, [], []);
    expect(slots).toHaveLength(0);
  });

  it("returns slots sorted ascending by startsAt", () => {
    const r1 = makeRule({ id: "r1", weekday: 1, start_time: "14:00", end_time: "15:00", slot_minutes: 30 });
    const r2 = makeRule({ id: "r2", weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const slots = computeSlots([r1, r2], MON, FRI, [], []);
    const times = slots.map((s) => s.startsAt.getTime());
    expect(times).toEqual([...times].sort((a, b) => a - b));
  });

  it("generates slots across multiple days in the range", () => {
    // Weekday 1 (Mon) and 5 (Fri) both in [MON, FRI]
    const r1 = makeRule({ id: "r1", weekday: 1, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const r2 = makeRule({ id: "r2", weekday: 5, start_time: "09:00", end_time: "10:00", slot_minutes: 30 });
    const slots = computeSlots([r1, r2], MON, FRI, [], []);
    expect(slots).toHaveLength(4); // 2 Mon + 2 Fri
  });
});

