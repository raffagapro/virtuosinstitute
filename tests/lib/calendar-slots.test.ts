describe("buildICS", () => {
  const params = {
    uid: "test-uid-123",
    title: "Cita Escolar",
    startsAt: new Date("2024-06-10T09:00:00Z"),
    endsAt: new Date("2024-06-10T09:30:00Z"),
  };

  it("starts with BEGIN:VCALENDAR and ends with END:VCALENDAR", () => {
    const ics = buildICS(params);
    expect(ics.startsWith("BEGIN:VCALENDAR")).toBe(true);
    expect(ics.trimEnd().endsWith("END:VCALENDAR")).toBe(true);
  });

  it("includes VEVENT block", () => {
    const ics = buildICS(params);
    expect(ics).toContain("BEGIN:VEVENT");
    expect(ics).toContain("END:VEVENT");
  });

  it("includes UID property", () => {
    const ics = buildICS(params);
    expect(ics).toContain("UID:test-uid-123");
  });

  it("includes SUMMARY with the title", () => {
    const ics = buildICS(params);
    expect(ics).toContain("SUMMARY:Cita Escolar");
  });

  it("includes DTSTART in UTC compact format", () => {
    const ics = buildICS(params);
    expect(ics).toContain("DTSTART:20240610T090000Z");
  });

  it("includes DTEND in UTC compact format", () => {
    const ics = buildICS(params);
    expect(ics).toContain("DTEND:20240610T093000Z");
  });

  it("includes optional DESCRIPTION when provided", () => {
    const ics = buildICS({ ...params, description: "Appointment note" });
    expect(ics).toContain("DESCRIPTION:");
    expect(ics).toContain("Appointment note");
  });

  it("uses CRLF line endings (\\r\\n)", () => {
    const ics = buildICS(params);
    expect(ics).toContain("\r\n");
  });

  it("folds lines longer than 75 characters", () => {
    const longTitle = "A".repeat(200);
    const ics = buildICS({ ...params, title: longTitle });
    const lines = ics.split("\r\n");
    for (const line of lines) {
      expect(line.length).toBeLessThanOrEqual(75);
    }
  });
});
