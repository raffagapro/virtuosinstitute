describe("buildGCalUrl", () => {
  const params = {
    title: "Cita en Coordinación",
    startsAt: new Date("2024-06-10T09:00:00Z"),
    endsAt: new Date("2024-06-10T09:30:00Z"),
  };

  it("returns a URL starting with the Google Calendar base", () => {
    const url = buildGCalUrl(params);
    expect(url).toMatch(/^https:\/\/calendar\.google\.com\/calendar\/r\/eventedit/);
  });

  it("includes encoded title in the 'text' parameter", () => {
    const url = buildGCalUrl(params);
    expect(url).toContain("text=");
    // URLSearchParams encodes spaces as '+'; replace before decoding.
    expect(decodeURIComponent(url.replace(/\+/g, " "))).toContain("Cita en Coordinación");
  });

  it("includes a 'dates' parameter in UTC compact format", () => {
    const url = buildGCalUrl(params);
    expect(url).toContain("dates=20240610T090000Z");
  });

  it("includes optional description when provided", () => {
    const url = buildGCalUrl({ ...params, description: "My note" });
    expect(decodeURIComponent(url.replace(/\+/g, " "))).toContain("My note");
  });

  it("includes optional location when provided", () => {
    const url = buildGCalUrl({ ...params, location: "Escuela" });
    expect(decodeURIComponent(url)).toContain("Escuela");
  });

  it("omits description and location when not provided", () => {
    const url = buildGCalUrl(params);
    expect(url).not.toContain("details=");
    expect(url).not.toContain("location=");
  });
});

